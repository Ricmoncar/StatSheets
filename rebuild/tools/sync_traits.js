// Generate web/src/app/core/game/traits-data.ts from the old site's traits.js.
//
// Until the cutover, traits.js at the repo root stays the one place traits are
// edited (the old site still loads it), and the new app is built from a copy
// generated here. Run it after any change to traits.js:
//
//     node rebuild/tools/sync_traits.js
//
// traits.js is EVALUATED (it is plain data) and the resulting tables written
// out, rather than copied as text: the file defines some keys twice (e.g.
// `grounded`, `ironclad`), where JavaScript silently keeps the last one and
// TypeScript refuses to compile. Evaluating gives exactly what the browser sees.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '../..');
const SRC = path.join(ROOT, 'traits.js');
const OUT = path.join(ROOT, 'web/src/app/core/game/traits-data.ts');
const TABLES = ['TRAITS', 'SHIMMYFUL_TRAITS', 'SHIMMYFUL_MYTHIC_TRAITS', 'SHIMMYFUL_EPIC_TRAITS', 'SHIMMYFUL_RARE_TRAITS', 'SHIMMYFUL_LEGENDARY_TRAITS'];

const src = fs.readFileSync(SRC, 'utf8');
const tables = vm.runInNewContext(src + `\n;({ ${TABLES.join(', ')} })`, {}, { filename: 'traits.js' });

// refuse anything JSON cannot carry faithfully
(function check(v, where) {
  if (typeof v === 'function' || v === undefined || (typeof v === 'number' && !isFinite(v))) {
    throw new Error(`traits.js holds a value JSON cannot represent at ${where}`);
  }
  if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) check(x, where + '.' + k);
})(tables, 'tables');

// keys defined twice inside the same table
const starts = TABLES.map(t => ({ t, at: src.search(new RegExp(`^const ${t} = \\{`, 'm')) })).sort((a, b) => a.at - b.at);
const dupes = [];
starts.forEach(({ t, at }, i) => {
  const body = src.slice(at, i + 1 < starts.length ? starts[i + 1].at : src.length);
  const keys = [...body.matchAll(/^  ([A-Za-z_0-9]+)\s*:\s*\{/gm)].map(m => m[1]);
  keys.filter((k, j) => keys.indexOf(k) !== j).forEach(k => dupes.push(`${t}.${k}`));
});

let out = '// GENERATED by rebuild/tools/sync_traits.js from the old site\'s traits.js.\n'
  + '// Do not edit by hand: edit traits.js and run the script again.\n'
  + (dupes.length ? `// traits.js defines these keys more than once; as in the browser, the last definition wins: ${[...new Set(dupes)].join(', ')}\n` : '')
  + "import type { TraitTable } from './trait-types';\n\n";
for (const name of TABLES) {
  out += `export const ${name}: TraitTable = ${JSON.stringify(tables[name], null, 1)};\n\n`;
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${TABLES.map(t => `${t} ${Object.keys(tables[t]).length}`).join(', ')}`);
